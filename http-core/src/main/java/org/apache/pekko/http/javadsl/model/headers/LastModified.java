package org.apache.pekko.http.javadsl.model.headers;

import org.apache.pekko.annotation.InternalApi;
import org.apache.pekko.http.javadsl.model.DateTime;

/**
 * Model for the `Last-Modified` header. Specification:
 * http://tools.ietf.org/html/draft-ietf-httpbis-p4-conditional-26#section-2.2
 */
public abstract class LastModified extends org.apache.pekko.http.scaladsl.model.HttpHeader {
  // Keep this rendering-only metadata in the non-serializable superclass.
  private transient StaticResourceOrigin staticResourceOrigin;

  public abstract DateTime date();

  public static LastModified create(DateTime date) {
    return new org.apache.pekko.http.scaladsl.model.headers.Last$minusModified(
        ((org.apache.pekko.http.scaladsl.model.DateTime) date));
  }

  /** INTERNAL API: the origin clock sample for a validator generated by a static resource route. */
  @InternalApi
  public static final class StaticResourceOrigin {
    private final long sampledAtMillis;
    private final boolean wasClamped;

    private StaticResourceOrigin(long sampledAtMillis, boolean wasClamped) {
      this.sampledAtMillis = sampledAtMillis;
      this.wasClamped = wasClamped;
    }

    public long sampledAtMillis() {
      return sampledAtMillis;
    }

    public boolean wasClamped() {
      return wasClamped;
    }

    public static LastModified createHeader(
        DateTime date, long sampledAtMillis, boolean wasClamped) {
      LastModified header = LastModified.create(date);
      header.staticResourceOrigin = new StaticResourceOrigin(sampledAtMillis, wasClamped);
      return header;
    }

    public static StaticResourceOrigin of(LastModified header) {
      return header.staticResourceOrigin;
    }
  }
}
